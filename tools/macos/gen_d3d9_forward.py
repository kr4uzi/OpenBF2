def build_all(m, fixture):
    files = {
        "ForwardWrappers.cpp": gen_wrappers(m),
        "ForwardFunctions.cpp": gen_functions(m),
        "ForwardChecks.inc": gen_checks(m),
        "ForwardNames.inc": gen_names(m),
        "ForwardRename.inc": gen_rename(m),
        "ForwardUnrename.inc": gen_unrename(m),
        "ForwardUndef.inc": gen_undef(m),
        "ForwardMacroValues.inc": gen_macro_values(m),
    }
    fx = {}
    if fixture:
        fx = {"FakeSdk.h": gen_fakesdk(m), "ForwardSdk.h": gen_fixture_sdk(m), "FakeObjects.h": gen_fakeobjects(m)}
    return files, fx


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-dir", type=Path, default=OUT_DEFAULT)
    ap.add_argument("--fixture-dir", type=Path)
    ap.add_argument("--check", action="store_true", help="fail if --out-dir differs from a fresh generation")
    a = ap.parse_args()
    m = Model((GFX / "D3D9Subset.h").read_text(), (GFX / "D3DX9Subset.h").read_text())
    files, fx = build_all(m, a.fixture_dir is not None)
    if a.check:
        bad = [n for n, t in files.items() if not (a.out_dir / n).exists() or (a.out_dir / n).read_text() != t]
        if bad:
            print("stale generated files (run tools/macos/gen_d3d9_forward.py): " + ", ".join(bad))
            return 1
        print(f"generated files current: {len(files)} files")
        return 0
    a.out_dir.mkdir(parents=True, exist_ok=True)
    for n, t in files.items():
        (a.out_dir / n).write_text(t)
    if a.fixture_dir:
        a.fixture_dir.mkdir(parents=True, exist_ok=True)
        for n, t in fx.items():
            (a.fixture_dir / n).write_text(t)
    ifs = m.wrappable()
    print(f"{len(m.ifaces)} interfaces ({len(m.concrete())} wrapper classes, {len(ifs)} wrappable), "
          f"{sum(len(m.flat_methods(n)) for n in m.concrete())} forwarded methods, "
          f"{len(m.functions)} free functions, {len(m.enums)} enums, {len(m.complete_structs)} structs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
