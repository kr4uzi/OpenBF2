#!/usr/bin/env python3
# [CHOSEN, not recovered] Generator for the G2w D3D9/D3DX forwarding backend.
#
# Reads Code/BF2/Platform/Gfx/D3D9Subset.h and D3DX9Subset.h and writes
#   Code/BF2/Platform/Gfx/D3D9Forward/Generated/
#     ForwardWrappers.cpp    one wrapper class per subset interface (+ state manager adapter)
#     ForwardFunctions.cpp   Direct3DCreate9 and the D3DX free functions
#     ForwardChecks.inc      static_asserts of subset enums / structs / macros against the SDK
#     ForwardNames.inc       Windows only: `namespace real` using-declarations and IID macros
#     ForwardRename.inc      Windows only: renames the subset's extern "C" functions in wrapper TUs
#     ForwardUndef.inc       Windows only: drops SDK macros the subset re-declares as constexpr
#     ForwardMacroValues.inc Windows only: captures SDK macro values for ForwardChecks.inc
# and, with --fixture-dir, a TEST FIXTURE (never used by a product build):
#     FakeSdk.h              a stand-in "real SDK" (namespace real) generated from the same subset
#     FakeObjects.h          recording fake implementations of every stand-in interface
#     ForwardSdk.h           the preamble the wrapper TU includes in the fixture build
#
# Two namespaces name the two worlds inside the wrapper TU: `sub::` is the subset (what the
# renderer sees) and `real::` is the SDK. Struct and enum types are identical by design, so they
# are converted with static_cast / reinterpret_cast; interface pointers are wrapped / unwrapped.
# See docs/macos-c-g2w-forward.md. Standard library only.
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GFX = ROOT / "Code/BF2/Platform/Gfx"
OUT_DEFAULT = GFX / "D3D9Forward/Generated"

BUILTIN = {"void", "int", "char", "short", "long", "float", "double", "unsigned", "signed", "bool"}
PASS_THROUGH = {"ID3DXInclude"}          # engine-implemented callback, same vtable shape as the SDK's
REVERSE = {"ID3DXEffectStateManager"}    # engine-implemented, called by real D3DX: needs an adapter
SKIP_WRAP = {"IUnknown"} | PASS_THROUGH | REVERSE
# Abstract interface -> (discriminating method, [(enumerator, concrete interface)]).
DISPATCH = {"IDirect3DBaseTexture9": ("GetType", [
    ("D3DRTYPE_TEXTURE", "IDirect3DTexture9"),
    ("D3DRTYPE_CUBETEXTURE", "IDirect3DCubeTexture9"),
    ("D3DRTYPE_VOLUMETEXTURE", "IDirect3DVolumeTexture9")])}
# Fake objects only: what Resource::GetType returns for each concrete fake.
FAKE_RTYPE = {"IDirect3DTexture9": "TEXTURE", "IDirect3DCubeTexture9": "CUBETEXTURE",
              "IDirect3DVolumeTexture9": "VOLUMETEXTURE", "IDirect3DSurface9": "SURFACE",
              "IDirect3DVertexBuffer9": "VERTEXBUFFER", "IDirect3DIndexBuffer9": "INDEXBUFFER"}
D3DX_MODULE = "d3dx9_25.dll"             # D3DX_SDK_VERSION 25, the generation the retail renderer binds
HEADER = "// GENERATED by tools/macos/gen_d3d9_forward.py from D3D9Subset.h / D3DX9Subset.h. Do not edit.\n"
# The recursive source sweeps of the other images must see an empty TU: only the seam build defines this.
GUARD_OPEN = "#if defined(BF2_GFX_FORWARD_TU)\n"
GUARD_CLOSE = "\n#endif // BF2_GFX_FORWARD_TU\n"
FIXTURE_HEADER = ("// TEST FIXTURE generated by tools/macos/gen_d3d9_forward.py --fixture-dir.\n"
                  "// A stand-in for the real SDK, built from the subset. Not used by any product build.\n")


# ----------------------------------------------------------------------------- model
class Type:
    def __init__(self, text):
        self.text = " ".join(text.split())
        self.tokens = re.findall(r"[A-Za-z_]\w*|\*|&", self.text)
        self.ptr = self.tokens.count("*")
        self.ref = "&" in self.tokens
        self.const = "const" in self.tokens
        words = [t for t in self.tokens if t not in ("const", "*", "&")]
        idents = [t for t in words if t not in BUILTIN]
        self.base = idents[0] if idents else (words[0] if words else "void")


class Method:
    def __init__(self, ret, name, args):
        self.ret, self.name = Type(ret), name
        self.params = [Type(a) for a in split_args(args)]


def split_args(s):
    s = s.strip()
    return [] if s in ("", "void") else [a.strip() for a in s.split(",")]


class Iface:
    def __init__(self, name, base, methods):
        self.name, self.base, self.methods = name, base, methods


class Model:
    def __init__(self, d3d_text, d3dx_text):
        d3d_text = re.sub(r"//[^\n]*", "", d3d_text)
        d3dx_text = re.sub(r"//[^\n]*", "", d3dx_text)
        # Everything before `using D3DCOLOR` is the non-Windows platform stand-in block.
        api = d3d_text[d3d_text.index("using D3DCOLOR"):] + "\n" + d3dx_text
        self.api = api
        self.enums = {}                      # name -> [enumerators]
        for m in re.finditer(r"enum\s+(\w+)\s*\{(.*?)\};", api, re.S):
            self.enums[m.group(1)] = [e.strip().split("=")[0].strip()
                                      for e in re.split(r",(?![^()]*\))", m.group(2)) if e.strip()]
        self.aliases = set(re.findall(r"^using\s+(\w+)\s*=", api, re.M))
        self.complete_structs, self.forward = [], []
        self.ifaces = {}
        for m in re.finditer(r"^struct\s+(I\w+)\s*(?::\s*(\w+))?\s*\{(.*?)\n\};", api, re.S | re.M):
            methods = [Method(r, n, a) for r, n, a in
                       re.findall(r"BF2_D3DX?_METHOD\(\s*([^,]+?)\s*,\s*(\w+)\s*,\s*\((.*?)\)\s*\)\s*;", m.group(3))]
            self.ifaces[m.group(1)] = Iface(m.group(1), m.group(2) or None, methods)
        for m in re.finditer(r"^struct\s+(\w+)\s*(?::\s*\w+\s*)?\{", api, re.M):
            if m.group(1) not in self.ifaces:
                self.complete_structs.append(m.group(1))
        for m in re.finditer(r"^struct\s+(\w+)\s*;", api, re.M):
            self.forward.append(m.group(1))
        # Interfaces that are only forward-declared are opaque (pass-through pointers).
        self.opaque = [n for n in self.forward if n not in self.ifaces]
        self.macros = sorted(set(n for n in re.findall(r"^#define\s+(\w+)", api, re.M)
                                 if not n.startswith("BF2_")))
        self.value_macros = [n for n in re.findall(r"^#define\s+(\w+)\s+\S", api, re.M)
                             if not n.startswith("BF2_")]
        self.constexprs = []
        for line in re.findall(r"^constexpr\s+\w+\s+(.*?);", api, re.M):
            self.constexprs += re.findall(r"(\w+)\s*=", line)
        # Free functions: `RET WINAPI Name(args);`
        self.functions = []
        for stmt in re.findall(r"^[A-Za-z_][^;{}]*?\bWINAPI\b[^;{}]*;", api, re.M | re.S):
            if stmt.startswith("using"):
                continue
            f = re.match(r"(?:extern\s+\"C\"\s+)?(.*?)\bWINAPI\s+(\w+)\s*\((.*)\)\s*;", " ".join(stmt.split()))
            args = []
            for a in split_args(f.group(3)):
                mm = re.match(r"(.*?)(\w+)$", a)
                args.append((mm.group(1).strip(), mm.group(2)))
            self.functions.append((f.group(1).strip(), f.group(2), args))
        self.d3dx_version = re.search(r"#define\s+D3DX_SDK_VERSION\s+(\d+)", api).group(1)
        self.check()

    def check(self):
        assert self.d3dx_version == "25", "D3DX_MODULE assumes D3DX_SDK_VERSION 25"
        for n, i in self.ifaces.items():
            assert i.base is None or i.base in self.ifaces or i.base == "IUnknown", n
        for n in DISPATCH:
            assert n in self.ifaces

    # name classification
    def declared(self):
        names = set(self.enums) | set(self.aliases) | set(self.complete_structs) | set(self.forward) | set(self.ifaces)
        for v in self.enums.values():
            names.update(v)
        names.update(self.constexprs)
        return names

    def kind(self, name):
        if name in self.ifaces:
            return "iface"
        if name in self.opaque or name in self.complete_structs:
            return "struct"
        if name in self.enums:
            return "enum"
        if name in self.aliases:
            return "alias"
        return "plain"

    def chain(self, name):
        out = []
        while name and name != "IUnknown":
            out.append(self.ifaces[name])
            name = self.ifaces[name].base
        return out[::-1]                      # base first, as the vtable lays them out

    def flat_methods(self, name):
        return [m for i in self.chain(name) for m in i.methods]

    def concrete(self):
        bases = {i.base for i in self.ifaces.values()}
        return [n for n in self.ifaces if n not in SKIP_WRAP and n not in bases]

    def wrappable(self):
        return [n for n in self.ifaces if n not in SKIP_WRAP and (n in self.concrete() or n in DISPATCH)]

    def render(self, t, ns):
        """Type text with every subset-declared identifier qualified by `ns::`.
        Aliases (D3DCOLOR, D3DXHANDLE) are plain scalars: the SDK spells them the same, unqualified."""
        decl = self.declared()
        out = []
        for tok in t.tokens:
            if tok in decl and not (ns == "real" and tok in self.aliases):
                tok = f"{ns}::{tok}"
            out.append(tok)
        return " ".join(out).replace(" *", "*").replace(" &", "&")


def iid_macro(n):
    return f"BF2_FWD_IID_{n}"


# ----------------------------------------------------------------------------- conversion
class Conv:
    """Converts one argument across the seam; returns (pre, expr, post) source fragments."""

    def __init__(self, model, down):
        self.m, self.down = model, down
        self.src, self.dst = ("sub", "real") if down else ("real", "sub")

    def arg(self, t, i, method):
        m, a = self.m, f"a{i}"
        k = m.kind(t.base) if t.base not in BUILTIN else "plain"
        if t.ref or k in ("plain", "alias"):
            return [], a, []
        cast = f"reinterpret_cast<{m.render(t, self.dst)}>({a})"
        if k == "enum":
            return ([], f"static_cast<{m.render(t, self.dst)}>({a})", []) if t.ptr == 0 else ([], cast, [])
        if k == "struct":
            assert t.ptr >= 1, (method.name, t.text)
            return [], cast, []
        # interface
        if t.base in REVERSE:
            assert self.down and t.ptr == 1
            return ([f"real::{t.base}* m{i} = {a} ? MakeStateManagerAdapter({a}) : nullptr;"],
                    f"m{i}", [f"if (m{i}) m{i}->Release();"])
        if t.base in PASS_THROUGH or t.base not in m.wrappable():
            return [], cast, []
        if t.ptr == 1:
            if self.down:
                return [], f"Real_{t.base}({a})", []
            return ([f"Borrowed<sub::{t.base}> b{i}(Adopt_{t.base}(AddRefd({a})));"], f"b{i}.get()", [])
        assert self.down and t.ptr == 2, (method.name, t.text)
        return ([f"real::{t.base}* o{i} = nullptr;"], f"{a} ? &o{i} : nullptr",
                [f"if ({a}) *{a} = Adopt_{t.base}(o{i});"])

    def method_body(self, meth, target):
        """Lines of one forwarding method. `target` is the expression naming the callee."""
        pre, args, post = [], [], []
        ps = meth.params
        for i, p in enumerate(ps):
            if self.down and p.base == "void" and p.ptr == 2 and i > 0 and ps[i - 1].base in ("REFIID", "REFGUID"):
                pre.append(f"void* o{i} = nullptr;")
                args.append(f"&o{i}")
                post.append(f"r = FinishIidOut(r, a{i - 1}, o{i}, a{i});")
                continue
            a, b, c = self.arg(p, i, meth)
            pre += a
            args.append(b)
            post += c
        call = f"{target}->{meth.name}({', '.join(args)})"
        ret = meth.ret
        retk = self.m.kind(ret.base) if ret.base not in BUILTIN else "plain"
        retexpr = "r"
        if retk == "enum" and ret.ptr == 0:
            retexpr = f"static_cast<{self.m.render(ret, self.src)}>(r)"
        if ret.base == "void" and ret.ptr == 0:
            return pre + [call + ";"] + post
        return pre + [f"auto r = {call};"] + post + [f"return {retexpr};"]


def params_decl(model, meth, ns):
    return ", ".join(f"{model.render(p, ns)} a{i}" for i, p in enumerate(meth.params))


# ----------------------------------------------------------------------------- wrappers
def gen_wrappers(m):
    L = [HEADER + GUARD_OPEN, '#include "ForwardSdk.h"', '#include "../ForwardRuntime.h"', "", "namespace bf2fwd {", ""]
    wr = m.wrappable()
    L.append("// Wrap / unwrap. Adopt_X takes over ONE reference of the real object; Real_X borrows.")
    for n in wr:
        L.append(f"sub::{n}* Adopt_{n}(real::{n}* r);")
        L.append(f"real::{n}* Real_{n}(sub::{n}* p);")
    L += ["real::ID3DXEffectStateManager* MakeStateManagerAdapter(sub::ID3DXEffectStateManager* mgr);", ""]
    for n in m.concrete():
        L += gen_wrapper_class(m, n)
    L += gen_adapter(m)
    for n in m.concrete():
        L += [f"sub::{n}* Adopt_{n}(real::{n}* r) {{ return AdoptT<Fwd_{n}, sub::{n}>(r); }}",
              f"real::{n}* Real_{n}(sub::{n}* p) {{ return p ? static_cast<Fwd_{n}*>(p)->real_ : nullptr; }}"]
    for n, (disc, cases) in DISPATCH.items():
        L += [f"sub::{n}* Adopt_{n}(real::{n}* r) {{", "    if (!r) return nullptr;",
              f"    switch (r->{disc}()) {{"]
        for e, c in cases:
            L.append(f"    case real::{e}: return Adopt_{c}(static_cast<real::{c}*>(r));")
        L += ["    default: Fatal(\"unexpected resource type for\", \"%s\"); }" % n, "}",
              f"real::{n}* Real_{n}(sub::{n}* p) {{", "    if (!p) return nullptr;",
              f"    switch (p->{disc}()) {{"]
        for e, c in cases:
            L.append(f"    case sub::{e}: return Real_{c}(static_cast<sub::{c}*>(p));")
        L += ["    default: Fatal(\"unexpected resource type for\", \"%s\"); }" % n, "}"]
    # IID dispatch: QueryInterface / GetContainer results.
    L += ["", "// Table of the interfaces QueryInterface and GetContainer can hand out.",
          "struct IidEntry { const GUID& (*iid)(); void* (*adopt)(void*); };"]
    for n in wr:
        if n in DISPATCH:
            continue
        L.append(f"static const GUID& Iid_{n}() {{ return {iid_macro(n)}; }}")
        L.append(f"static void* AdoptVoid_{n}(void* p) {{ return Adopt_{n}(static_cast<real::{n}*>(p)); }}")
    L += ["static const GUID& Iid_IUnknown() { return BF2_FWD_IID_IUnknown; }",
          "static void* AdoptVoid_IUnknown(void* p) { return AdoptUnknown(static_cast<::IUnknown*>(p)); }",
          "static const IidEntry kIids[] = {", "    { &Iid_IUnknown, &AdoptVoid_IUnknown },"]
    L += [f"    {{ &Iid_{n}, &AdoptVoid_{n} }}," for n in wr if n not in DISPATCH]
    L += ["};",
          "void* WrapByIid(REFIID iid, void* real) {",
          "    for (const IidEntry& e : kIids)",
          "        if (std::memcmp(&iid, &e.iid(), sizeof(GUID)) == 0) return e.adopt(real);",
          "    return nullptr;",
          "}", "", "} // namespace bf2fwd", "",
          "// C bridges for ForwardFunctions.cpp, which sees only the global subset types.", ]
    for n in wr:
        L.append(f'extern "C" void* bf2fwd_adopt_{n}(void* r) {{ return bf2fwd::Adopt_{n}(static_cast<real::{n}*>(r)); }}')
        L.append(f'extern "C" void* bf2fwd_real_{n}(void* p) {{ return bf2fwd::Real_{n}(static_cast<sub::{n}*>(p)); }}')
    L += ["", '#include "ForwardChecks.inc"']
    return "\n".join(L) + GUARD_CLOSE


def gen_wrapper_class(m, n):
    L = [f"class Fwd_{n} final : public FwdBase<Fwd_{n}, sub::{n}, real::{n}> {{",
         "public:",
         f"    explicit Fwd_{n}(real::{n}* r) : FwdBase(r) {{}}"]
    down = Conv(m, True)
    for meth in m.flat_methods(n):
        L.append(f"    {m.render(meth.ret, 'sub')} STDMETHODCALLTYPE {meth.name}({params_decl(m, meth, 'sub')}) override {{")
        L += ["        " + x for x in down.method_body(meth, "real_")]
        L.append("    }")
    L += ["};", ""]
    return L


def gen_adapter(m):
    n = "ID3DXEffectStateManager"
    L = ["// Real D3DX calls this object; it forwards to the engine's subset state manager.",
         f"class StateManagerAdapter final : public real::{n} {{", "public:",
         f"    explicit StateManagerAdapter(sub::{n}* mgr) : mgr_(mgr), refs_(1) {{ mgr_->AddRef(); }}",
         "    HRESULT STDMETHODCALLTYPE QueryInterface(REFIID iid, void** out) override {",
         "        if (!out) return E_NOINTERFACE;",
         f"        if (SameIid(iid, BF2_FWD_IID_IUnknown) || SameIid(iid, {iid_macro(n)})) {{ *out = this; AddRef(); return S_OK; }}",
         "        *out = nullptr; return E_NOINTERFACE;", "    }",
         "    ULONG STDMETHODCALLTYPE AddRef() override { return static_cast<ULONG>(++refs_); }",
         "    ULONG STDMETHODCALLTYPE Release() override {",
         "        long r = --refs_;",
         "        if (r == 0) { mgr_->Release(); delete this; }",
         "        return static_cast<ULONG>(r);", "    }"]
    up = Conv(m, False)
    for meth in m.ifaces[n].methods:
        L.append(f"    {m.render(meth.ret, 'real')} STDMETHODCALLTYPE {meth.name}({params_decl(m, meth, 'real')}) override {{")
        L += ["        " + x for x in up.method_body(meth, "mgr_")]
        L.append("    }")
    L += ["private:", f"    sub::{n}* mgr_;", "    std::atomic<long> refs_;", "};",
          f"real::{n}* MakeStateManagerAdapter(sub::{n}* mgr) {{ return new StateManagerAdapter(mgr); }}", ""]
    # The prototype must be visible to the wrapper classes, so it is emitted up front as well.
    return L


# ----------------------------------------------------------------------------- free functions
def gen_functions(m):
    wr = set(m.wrappable())
    L = [HEADER + GUARD_OPEN, '#include "../../D3DX9Subset.h"', "", "// Bridges exported by ForwardWrappers.cpp (void* only: that TU names the subset in a namespace).",
         'extern "C" void* bf2fwd_GetProc(const char* module, const char* name);']
    for n in sorted(wr):
        L.append(f'extern "C" void* bf2fwd_adopt_{n}(void* r);')
        L.append(f'extern "C" void* bf2fwd_real_{n}(void* p);')
    L.append("")
    for ret, name, args in m.functions:
        module = "d3d9.dll" if name == "Direct3DCreate9" else D3DX_MODULE
        tdef, call, pre, post = [], [], [], []
        for i, (ty, an) in enumerate(args):
            t = Type(ty)
            if t.base in wr and t.ptr == 1:
                tdef.append("void*")
                call.append(f"bf2fwd_real_{t.base}({an})")
            elif t.base in wr and t.ptr == 2:
                tdef.append("void**")
                pre.append(f"void* o{i} = nullptr;")
                call.append(f"{an} ? &o{i} : nullptr")
                post.append(f"if ({an}) *{an} = static_cast<{t.base}*>(bf2fwd_adopt_{t.base}(o{i}));")
            else:
                tdef.append(ty)
                call.append(an)
        rt = Type(ret)
        wrap_ret = rt.base in wr and rt.ptr == 1   # Direct3DCreate9
        assert rt.base not in wr or wrap_ret, name
        sig = ", ".join(f"{ty} {an}" for ty, an in args)
        L += [f'extern "C" {ret} WINAPI {name}({sig}) {{',
              f"    typedef {'void*' if wrap_ret else ret} (WINAPI *Fn)({', '.join(tdef) or 'void'});",
              f'    static Fn fn = reinterpret_cast<Fn>(bf2fwd_GetProc("{module}", "{name}"));']
        L += ["    " + x for x in pre]
        invoke = f"fn({', '.join(call)})"
        if ret == "void":
            L += [f"    {invoke};"] + ["    " + x for x in post]
        elif wrap_ret:
            L += [f"    void* r = {invoke};", f"    return static_cast<{ret}>(bf2fwd_adopt_{rt.base}(r));"]
        else:
            L += [f"    {ret} r = {invoke};"] + ["    " + x for x in post] + ["    return r;"]
        L += ["}", ""]
    return "\n".join(L) + GUARD_CLOSE


# ----------------------------------------------------------------------------- checks
def gen_checks(m):
    L = [HEADER.rstrip(), "// Included at the end of ForwardWrappers.cpp. A failure means the subset is not the SDK's layout.", ""]
    for s in m.complete_structs:
        L.append(f'static_assert(sizeof(sub::{s}) == sizeof(real::{s}) && alignof(sub::{s}) == alignof(real::{s}), "layout of {s}");')
    for e, vals in m.enums.items():
        L.append(f'static_assert(sizeof(sub::{e}) == sizeof(real::{e}), "size of enum {e}");')
        for v in vals:
            L.append(f'static_assert(static_cast<long long>(sub::{v}) == static_cast<long long>(real::{v}), "{v}");')
    L += ["", "#ifdef BF2_FWD_SDK_MACROS   // Windows: ForwardMacroValues.inc captured the SDK values"]
    for n in m.value_macros:
        L.append(f'static_assert(static_cast<std::uint32_t>({n}) == sdkv_{n}, "{n}");')
    for n in m.constexprs:
        L.append(f'static_assert(static_cast<std::uint32_t>(sub::{n}) == sdkv_{n}, "{n}");')
    L += ["#endif", ""]
    return "\n".join(L)


# ----------------------------------------------------------------------------- Windows includes
def gen_names(m):
    L = [HEADER.rstrip(), "// Windows only: included by ForwardSdk.h after <d3d9.h>/<d3dx9.h>.", "namespace real {"]
    for n in sorted(m.declared() - m.aliases - set(m.constexprs)):
        L.append(f"using ::{n};")
    L.append("}")
    L.append("#define BF2_FWD_IID_IUnknown __uuidof(::IUnknown)")
    for n in m.ifaces:
        if n in PASS_THROUGH:
            continue
        L.append(f"#define {iid_macro(n)} " + (f"IID_{n}" if n.startswith("ID3DX") else f"__uuidof(::{n})"))
    return "\n".join(L) + "\n"


def gen_rename(m):
    return HEADER + "".join(f"#define {n} BF2Sub_{n}\n" for _, n, _ in m.functions)


def gen_unrename(m):
    return "".join(f"#undef {n}\n" for _, n, _ in m.functions)


def gen_undef(m):
    return HEADER + "".join(f"#undef {n}\n" for n in sorted(set(m.macros) | set(m.constexprs)))


def gen_macro_values(m):
    L = [HEADER.rstrip(), "#define BF2_FWD_SDK_MACROS 1"]
    for n in m.value_macros + m.constexprs:
        L.append(f"static constexpr std::uint32_t sdkv_{n} = static_cast<std::uint32_t>({n});")
    return "\n".join(L) + "\n"


# ----------------------------------------------------------------------------- test fixture
def gen_fakesdk(m):
    L = [FIXTURE_HEADER.rstrip(), "#pragma once", '#include "D3DX9Subset.h"', "",
         "namespace real {"]
    for n in sorted(m.declared() - m.aliases - set(m.constexprs) - set(m.ifaces)):
        L.append(f"using ::{n};")
    for n in m.ifaces:
        if n in PASS_THROUGH:
            L.append(f"using ::{n};")
        elif n != "IUnknown":
            L.append(f"struct {n};")
    for n, ifc in m.ifaces.items():
        if n in PASS_THROUGH:
            continue
        L.append(f"struct {n} : {ifc.base or 'IUnknown'} {{")
        for meth in ifc.methods:
            L.append(f"    virtual {m.render(meth.ret, 'real')} STDMETHODCALLTYPE {meth.name}"
                     f"({params_decl(m, meth, 'real')}) = 0;")
        L.append("};")
    L += ["}", "namespace sub {"]
    for n in sorted(m.declared()):
        L.append(f"using ::{n};")
    L += ["}", ""]
    return "\n".join(L)


def gen_fixture_sdk(m):
    L = [FIXTURE_HEADER.rstrip(), "#pragma once", '#include "FakeSdk.h"',
         "#include <atomic>", "#include <cstdint>", "#include <cstdio>", "#include <cstdlib>", "#include <cstring>",
         "#include <mutex>", "#include <string>", "#include <unordered_map>", "",
         "namespace bf2fake { const GUID& Iid(const char* name); }"]
    L.append("#define BF2_FWD_IID_IUnknown ::bf2fake::Iid(\"IUnknown\")")
    for n in m.ifaces:
        L.append(f"#define {iid_macro(n)} ::bf2fake::Iid(\"{n}\")")
    L.append("")
    return "\n".join(L)


