#!/usr/bin/env python3
"""Generate docs/progress.md from the five committed function ledgers.

    python3 tools/tracks/progress.py [--check] [--root PATH]
    python3 tools/tracks/progress.py --refresh-markers

Standard library only. --check is read-only, offline and needs no retail images.
Summary prose and totals are never inputs: only a summary's 'Generated by ... at
<hash>' line supplies provenance. Client provenance comes from verdict commits.
--refresh-markers explicitly runs the slower source scan before generating the page.
The scan's table is saved as CSV: its last column is often empty, and a tab-separated
line would then end in a tab.
"""

import argparse
import csv
from pathlib import Path
import re
import subprocess
import sys
import tempfile

import client_ledger as client

REPO = Path(__file__).resolve().parents[2]
CONTRACT = ("image", "address", "size", "symbol", "file", "status", "commit")
PARTS = (
    ("Bot AI", "ai-reconstruct", "libaidll.so", ("done", "stop", "todo", "skip-debug", "skip-lib")),
    ("Renderer", "tracks/rend", "RendDX9.dll", ("done", "chosen", "stop", "todo", "skip")),
    ("Menu player", "tracks/swf", "SwiffPlayer.dll", ("done", "chosen", "stop", "unattributed", "todo")),
    ("Server network, files, console", "tracks/srv", "bf2", ("done", "chosen", "stop", "todo", "skip")),
    ("Client program", "tracks/client", "BF2.exe", tuple(client.STATUSES)),
)
MARKER_PATHS = tuple("Code/BF2/" + name for name in
                     ("Game", "Menu", "Core", "Scene", "Physics", "Sound", "Animation", "IO"))
MARKERS = "docs/tracks/markers.csv"
MARKER_FIELDS = ("kind", "file", "line", "function", "note")
MARKER_KINDS = {
    "abort": "A definition or namespace-scope macro that stops at a live frontier.",
    "free": "A frontier comment attached to no function (for example a field or file header).",
    "decl": "A frontier-tagged declaration with a matching non-stopping definition in the scanned files.",
    "partial": "A non-stopping definition with a frontier comment inside its body; execution continues past a documented gap.",
    "stale": "A frontier-tagged definition with neither a stop nor frontier text in its body; it may be a stale tag, a cross-reference or a silent partial body.",
    "seam": "A definition calling a report-and-continue seam helper.",
}
ATTR_CLASSES = ("cited", "matched", "inlined", "stl", "crt", "compiler", "editor", "missing")
CLIENT_GROUPS = (
    ("Nothing client-specific to review", ("none",)),
    ("Compared one by one", client.COMPARED),
    ("Left out after a sample", ("skipped",)),
    ("Not reviewed yet", ("todo",)),
    ("Client-only file taken as covered", ("client-tu",)),
)


def load_part(root, directory, image, statuses):
    path = root / "docs" / directory / "ledger.csv"
    if directory == "tracks/client":
        return client.load_ledger(path)
    required = CONTRACT[1:] if directory == "ai-reconstruct" else CONTRACT
    rows, _ = client.read_table(path, required)
    seen = set()
    for row in rows:
        if directory == "ai-reconstruct":
            row["image"] = image
        if row["image"] not in ({image, "BF2.exe"} if directory == "tracks/rend" else {image}):
            raise ValueError(f"{path}: unexpected image {row['image']!r}")
        if not re.fullmatch(r"0x[0-9a-fA-F]+", row["address"]):
            raise ValueError(f"{path}: invalid address {row['address']!r}")
        key = row["image"], int(row["address"], 16)
        if key in seen:
            raise ValueError(f"{path}: duplicate image+address {key}")
        seen.add(key)
        if not re.fullmatch(r"[0-9]+", row["size"]):
            raise ValueError(f"{path}: invalid size at {row['address']}")
        if row["status"] not in statuses:
            raise ValueError(f"{path}: unknown status {row['status']!r}")
    # Validate all renderer rows, including the executable rows excluded from totals.
    return [row for row in rows if row["image"] == image]


def generation_commit(path):
    if not path.exists():
        return "unknown"
    match = re.search(r"^Generated by [^\n]+? at `?([0-9a-f]{7,40})`?(?=[\s.,]|$)",
                      path.read_text(encoding="utf-8"), re.M)
    return f"`{match.group(1)}`" if match else "unknown"


def load_attribution(root):
    path = root / "docs/tracks/rend/attribution.csv"
    rows, _ = client.read_table(path, ("address", "class"))
    out = {}
    for row in rows:
        if not re.fullmatch(r"0x[0-9a-fA-F]+", row["address"]):
            raise ValueError(f"{path}: invalid address")
        address = int(row["address"], 16)
        if address in out or row["class"] not in (*ATTR_CLASSES, ""):
            raise ValueError(f"{path}: duplicate address or unknown attribution class")
        out[address] = row["class"]
    return out


def load_markers(root):
    path = root / MARKERS
    rows, _ = client.read_table(path, MARKER_FIELDS)
    for row in rows:
        if (row["kind"] not in MARKER_KINDS or not re.fullmatch(r"[1-9][0-9]*", row["line"]) or
                not any(row["file"].startswith(p + "/") for p in MARKER_PATHS) or
                ".." in row["file"].split("/")):
            raise ValueError(f"{path}: invalid marker row")
    return rows


def refresh_markers(root):
    """Run the source marker scan over MARKER_PATHS and save its table as CSV."""
    with tempfile.TemporaryDirectory() as tmp:
        scan = Path(tmp) / "markers.tsv"
        subprocess.run([sys.executable, str(root / "tools/tracks/marker_check.py"),
                        *MARKER_PATHS, "--tsv", str(scan)], cwd=root, check=True)
        rows, _ = client.read_table(scan, MARKER_FIELDS, "\t")
    with (root / MARKERS).open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, MARKER_FIELDS, lineterminator="\n", extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def rows_with(rows, statuses):
    return [row for row in rows if row["status"] in statuses]


def build_page(root):
    root = Path(root)
    parts = [load_part(root, directory, image, statuses)
             for _, directory, image, statuses in PARTS]
    attribution = load_attribution(root)
    markers = load_markers(root)
    lines = ["# Reconstruction progress", "",
             "This page is generated from the repository's five function ledgers by "
             "`python3 tools/tracks/progress.py`. The first four count retail functions with source "
             "bodies; the client ledger records client-behaviour review verdicts. These are inventories, "
             "not proof of equivalent behaviour, working gameplay or a percentage of the whole engine.", "",
             "## Ledger summary", ""]
    summary_rows = []
    for (name, directory, image, _), rows in zip(PARTS, parts):
        is_client = directory == "tracks/client"
        open_statuses = (("todo", "gap", "cannot-tell", "skipped") if is_client else
                         ("todo", "unattributed", "skip-debug"))
        opened = rows_with(rows, open_statuses)
        size = client.totals(rows)[1]
        library = ([r for r in rows if r["kind"] == "lib"] if is_client else
                   rows_with(rows, ("skip", "skip-lib")))
        summary_rows.append((name, image, len(rows), "Not measured" if is_client else len(rows_with(rows, ("done",))),
                             len(rows_with(rows, ("deliberate",) if is_client else ("chosen",))),
                             "Not measured" if is_client else len(rows_with(rows, ("stop",))),
                             len(library), len(opened), f"{100 * client.totals(opened)[1] / size if size else 0:.1f}%"))
    lines += client.table(["Part", "Retail image", "Functions", "Functions with a source body",
                           "Deliberate replacements", "Stops", "Library or compiler code", "Open functions",
                           "Open share of retail bytes"], summary_rows)
    lines += ["Key (the ledgers' own words):", "",
              "- Bot AI: source body = `done`; stops = `stop`; library/compiler = `skip-lib`; open = `todo` + `skip-debug` (debug-drawing code set aside).",
              "- Renderer and server: source body = `done`; deliberate replacements = `chosen`; stops = `stop`; library/compiler = `skip`; open = `todo`.",
              "- Menu player: source body = `done`; deliberate replacements = `chosen`; stops = `stop`; open = `todo` + `unattributed` (no established attribution). No separate library/compiler status exists.",
              "- Client: deliberate replacements = `deliberate`; library/compiler = kind `lib`; open review work = `todo` + `gap` + `cannot-tell` + `skipped`. These are review categories; source-body and stop counts are not measured. `present` and `client-tu` do not establish a whole-program source-body count.",
              "", "Open counts exclude the separate stop column in the first four ledgers. "
              "Library/compiler counts use only the listed skip statuses, not renderer attribution classes. "
              "Bytes are the sum of retail function sizes, not unique image coverage; zero-size functions still count as rows.", "",
              "The renderer row counts only RendDX9.dll; its BF2.exe rows overlap the client ledger and are excluded.", "",
              "Recorded ledger revisions (generation hashes, not a claim of current-source coverage):", ""]
    lines += client.table(["Part", "Recorded revision"], [
        (name, client.review_commits(rows) if directory == "tracks/client" else
         generation_commit(root / "docs" / directory / "ledger-summary.md"))
        for (name, directory, _, _), rows in zip(PARTS, parts)])
    lines += ["## Renderer open rows by attribution", "",
              "Only current RendDX9.dll `todo` rows are joined to the attribution table by address. "
              "Attribution does not change their ledger status.", ""]
    renderer_open = rows_with(parts[1], ("todo",))
    attributed = [{**r, "class": attribution.get(int(r["address"], 16)) or "No attribution class"}
                  for r in renderer_open]
    lines += client.table(["Attribution class", "Open rows", "Retail bytes"], [
        *client.breakdown(attributed, "class", (*ATTR_CLASSES, "No attribution class")),
        ("Total", *client.totals(renderer_open))])
    lines += ["`missing` means unexplained so far; it has not been shown to be unwritten code.", "",
              "## Client program", ""]
    rows = parts[4]
    lines += [f"Review commit(s): {client.review_commits(rows)}. Verdicts describe source at each row's "
              "`commit` value; later fixes are not reflected yet. `none` and `todo` carry no review commit. "
              "The comparison pairs BF2.exe with bf2_w32ded.exe; Linux names supply symbols where known.", ""]
    lines += client.table(["Review group", "Functions", "Retail bytes"], [
        *[(name, *client.totals(rows_with(rows, statuses))) for name, statuses in CLIENT_GROUPS],
        ("Total", *client.totals(rows))])
    lines += ["The client-only-file group (`client-tu`) was taken as covered without individual comparison; "
              "it is shown separately so every row belongs to exactly one group.", "",
              "Verdicts of rows compared one by one:", ""]
    compared = rows_with(rows, client.COMPARED)
    lines += client.table(["Status", "Meaning", "Functions", "Retail bytes"], [
        *[(status, client.STATUSES[status], *client.totals(rows_with(compared, (status,))))
          for status in client.COMPARED], ("Total", "Compared one by one", *client.totals(compared))])
    lines += ["Kind by status for all client rows. Each cell is functions / retail bytes; "
              "the [client ledger summary](tracks/client/ledger-summary.md) defines every kind and status.", ""]
    lines += client.matrix(rows, "kind", client.KINDS, "status", client.STATUSES)
    lines += ["`unmatched` means no dedicated-server counterpart was found; it does not prove the function is client-only.", "",
              "`skipped` means left out after a sample of its group; those rows were not individually verified.", "",
              "## Declared holes", "",
              "These are source marker findings from the committed [marker table](tracks/markers.csv), "
              "not additional retail functions to add to the ledgers. Findings can overlap ledger rows "
              "or describe the same function more than once. The scan does not evaluate conditions; "
              "a conditional stop is still counted. The table is a saved scan, not a scan run by `--check`.", ""]
    lines += client.table(["Marker kind", "Findings", "Meaning"], [
        *[(kind, sum(r["kind"] == kind for r in markers), meaning) for kind, meaning in MARKER_KINDS.items()],
        ("Total", len(markers), "Source marker findings")])
    directories = [path.rsplit("/", 1)[-1] for path in MARKER_PATHS]
    lines += client.table(["Directory under Code/BF2", "Findings"], [
        *[(name, sum(r["file"].split("/")[2] == name for r in markers)) for name in sorted(directories)],
        ("Total", len(markers))])
    lines += ["## Not measured yet", "",
              "Shared game code (objects, game logic, physics and animation) has no ledger of its own. "
              "Sound (BF2Audio and BF2OpenAL), the voice server and the Python host have none either. "
              "Some shared functions appear in the existing image ledgers; that does not make a complete inventory of these subsystems.", "",
              "## How these numbers are produced", "",
              "The page and its check read only committed tables and recorded revision lines. "
              "Regenerating the original function ledgers needs the inputs below. Retail images and "
              "local binary-analysis exports are not included in the repository.", ""]
    lines += client.table(["Part", "Ledger command", "Inputs needed to regenerate the ledger"], [
        ("Bot AI", "`python3 tools/ai-reconstruct/build_ledger.py --binary RETAIL_LIBAIDLL`",
         "Symbolized retail Linux ia-32 libaidll.so, source/manifests, console bindings; objdump, c++filt and git."),
        ("Renderer", "`python3 tools/tracks/rend_ledger.py --export out/rend-ghidra`",
         "Ghidra function exports from retail RendDX9.dll and BF2.exe, source; git. Attribution is a separate committed input (tools/tracks/attrib/)."),
        ("Menu player", "`python3 tools/tracks/swf_align.py --export SWF_EXPORT --history GAMESWF_HISTORY --binary RETAIL_SWIFFPLAYER`, then `python3 tools/tracks/swf_ledger.py`",
         "Retail SwiffPlayer.dll, its Ghidra exports, gameswf svn-r586 and tu-testbed rel-2004-05-12 checkouts, source; objdump. The second command needs out/swf-align tables/provenance plus committed completion overrides. The ledger CSV alone cannot regenerate its summary."),
        ("Server network, files, console", "`python3 tools/tracks/srv_ledger.py --binary RETAIL_BF2`",
         "Symbolized retail Linux ia-32 bf2 and source; objdump, c++filt and git."),
        ("Client program", "`python3 tools/tracks/client_ledger.py --import TABLE.tsv --reviewed COMMIT`",
         "Quoted client review TSV and its reviewed source commit. That working table is not published; producing reviews requires retail BF2.exe and bf2_w32ded.exe comparisons. The public CSV suffices for validation and its summary."),
    ])
    lines += ["Uppercase command arguments are placeholders for locally supplied inputs.", "",
              "Refresh the declared-hole table explicitly (the source scan is slower):", "", "```sh",
              "python3 tools/tracks/progress.py --refresh-markers", "```", "",
              "This runs `tools/tracks/marker_check.py` over " + ", ".join(f"`{p}`" for p in MARKER_PATHS) + ".", "",
              "Regenerate and check the page and client summary without retail images or network access:", "", "```sh",
              "python3 tools/tracks/client_ledger.py",
              "python3 tools/tracks/progress.py",
              "python3 tools/tracks/client_ledger.py --check",
              "python3 tools/tracks/progress.py --check", "```", "",
              "The checks validate table contracts and generated text. They do not compare source with "
              "retail instructions, update review verdicts, refresh source markers, or test a build or gameplay.", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=REPO, help="repository root (also useful for fixtures)")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--refresh-markers", action="store_true", help="rerun the source marker scan before generating")
    args = parser.parse_args(argv)
    if args.check and args.refresh_markers:
        parser.error("--check is read-only and cannot be combined with --refresh-markers")
    try:
        if args.refresh_markers:
            refresh_markers(args.root)
        page = build_page(args.root)
        path = args.root / "docs/progress.md"
        if args.check:
            return 0 if client.check_text(path, page) else 1
        path.write_text(page, encoding="utf-8")
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"progress.py: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
